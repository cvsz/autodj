#!/bin/bash
# Camfrog AutoDJ - Self-Extracting 7zip Installer Builder (Linux)
# Creates a self-extracting .exe installer using 7zip
# No Wine/NSIS required - builds on Linux, runs on Windows

set -euo pipefail

VERSION="${1:-0.2.5}"
SRCDIR="${2:-dist}"
OUTDIR="${3:-dist}"

echo "=========================================="
echo "Camfrog AutoDJ - 7zip SFX Installer Builder (Linux)"
echo "=========================================="
echo "Version: $VERSION"
echo "Source:  $SRCDIR"
echo "Output:  $OUTDIR"
echo

# Check for 7zip
if ! command -v 7z >/dev/null 2>&1; then
    echo "ERROR: 7z not found. Install with: sudo apt install p7zip-full"
    exit 1
fi
echo "Found 7z: $(7z | head -1)"

# Project root
PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"

# Output directory is project root's dist
REAL_OUTDIR="$PROJECT_ROOT/dist"

# Create staging directory
STAGING_DIR="${SRCDIR}_staging"
rm -rf "$STAGING_DIR"
mkdir -p "$STAGING_DIR"

# Copy required files to staging
echo "Preparing staging directory..."
cp "$PROJECT_ROOT/dist/AutoDJ.exe" "$STAGING_DIR/"
cp "$PROJECT_ROOT/app.ico" "$STAGING_DIR/"
cp "$PROJECT_ROOT/config.example.toml" "$STAGING_DIR/"
cp "$PROJECT_ROOT/README.md" "$STAGING_DIR/"
cp "$PROJECT_ROOT/CHANGELOG.md" "$STAGING_DIR/"
cp "$PROJECT_ROOT/ABOUT.md" "$STAGING_DIR/LICENSE.md"
cp "$PROJECT_ROOT/install.ps1" "$STAGING_DIR/"
# uninstall.ps1 is generated by install.ps1, copy if exists
if [[ -f "$PROJECT_ROOT/uninstall.ps1" ]]; then
    cp "$PROJECT_ROOT/uninstall.ps1" "$STAGING_DIR/"
fi
cp "$PROJECT_ROOT/run_autodj.py" "$STAGING_DIR/"

# Copy optional directories
for dir in camfrog_autodj docs tools; do
    if [[ -d "$PROJECT_ROOT/$dir" ]]; then
        cp -r "$PROJECT_ROOT/$dir" "$STAGING_DIR/"
    fi
done

cd "$STAGING_DIR"

REQUIRED_FILES=(
    "AutoDJ.exe"
    "app.ico"
    "config.example.toml"
    "README.md"
    "CHANGELOG.md"
    "LICENSE.md"
    "install.ps1"
    "uninstall.ps1"
    "run_autodj.py"
)

echo "Checking required files..."
for f in "${REQUIRED_FILES[@]}"; do
    if [[ ! -f "$f" ]]; then
        echo "  WARNING: Missing $f"
    else
        echo "  [OK] $f"
    fi
done

# Create 7z SFX config
SFX_CONFIG=$(cat <<'EOF'
; Camfrog AutoDJ - 7zip SFX Configuration
; Auto-extracts to temp folder and runs install.ps1

Setup=install.ps1
Title="Camfrog AutoDJ Setup"
BeginPrompt="Camfrog AutoDJ ${VERSION} Setup\n\nThis will install Camfrog AutoDJ on your computer.\n\nClick OK to continue."
FinishMessage="Camfrog AutoDJ ${VERSION} has been installed successfully!\n\nYou can now run it from the Start Menu or Desktop shortcut."
ExtractTitle="Extracting files..."
OverwriteMode=2
RunProgram="powershell.exe -NoProfile -ExecutionPolicy Bypass -File install.ps1"
AutoInstall=1
GUIMode=2
EOF
)

# Replace version placeholder
SFX_CONFIG="${SFX_CONFIG//\${VERSION}/$VERSION}"

# Write SFX config
echo "$SFX_CONFIG" > config.txt

# Build SFX installer
INSTALLER_NAME="Camfrog-AutoDJ-Setup-${VERSION}.exe"
SFX_MODULE=""

# Try to find 7zip SFX module
for path in \
    "/usr/lib/p7zip/7zCon.sfx" \
    "/usr/lib/x86_64-linux-gnu/p7zip/7zCon.sfx" \
    "/usr/share/p7zip/7zCon.sfx" \
    "/usr/lib/p7zip/7z.sfx" \
    "/usr/libexec/p7zip/7zCon.sfx"; do
    if [[ -f "$path" ]]; then
        SFX_MODULE="$path"
        break
    fi
done

if [[ -z "$SFX_MODULE" ]]; then
    echo "ERROR: 7zip SFX module (7zCon.sfx) not found."
    echo "Install p7zip-full: sudo apt install p7zip-full"
    exit 1
fi

echo "Building SFX installer: $INSTALLER_NAME..."
echo "Using SFX module: $SFX_MODULE"

# Create the archive (excluding the SFX module and config)
7z a -t7z -mx=9 -mfb=64 -md=32m -ms=on archive.7z \
    AutoDJ.exe \
    app.ico \
    config.example.toml \
    README.md \
    CHANGELOG.md \
    LICENSE.md \
    install.ps1 \
    uninstall.ps1 \
    run_autodj.py \
    camfrog_autodj/ \
    docs/ \
    tools/ 2>/dev/null || true

# Prepend SFX module + config to archive
cat "$SFX_MODULE" config.txt archive.7z > "$REAL_OUTDIR/$INSTALLER_NAME"

# Cleanup
rm -f config.txt archive.7z
cd "$PROJECT_ROOT"
rm -rf "$STAGING_DIR"

# Verify
if [[ -f "$OUTDIR/$INSTALLER_NAME" ]]; then
    SIZE_MB=$(du -m "$OUTDIR/$INSTALLER_NAME" | cut -f1)
    echo ""
    echo "=========================================="
    echo "SFX Installer built successfully!"
    echo "=========================================="
    echo "File: $OUTDIR/$INSTALLER_NAME"
    echo "Size: ${SIZE_MB} MB"
    echo ""
    echo "Note: This is a self-extracting archive that runs install.ps1 on extraction."
    echo "      It requires PowerShell and admin rights for VB-Cable installation."
    echo ""
    echo "Next steps:"
    echo "  1. Test on clean Windows VM"
    echo "  2. Sign with signtool (on Windows):"
    echo "     signtool sign /f cert.pfx /p password /t http://timestamp.digicert.com \"$INSTALLER_NAME\""
    echo "  3. Upload to GitHub Releases"
else
    echo "ERROR: Installer not found"
    exit 1
fi