#!/usr/bin/env python3
"""Generate the PyInstaller spec for AutoDJ.exe -- single source of build flags.

``build.ps1`` (Windows) and ``scripts/build_exe_linux.sh`` (Wine) both
regenerate ``AutoDJ.spec`` from this file before every build, so the
PyInstaller options live in exactly one place.  Edit this file, not the
generated spec (``AutoDJ.spec`` is a gitignored build artifact).

Flag mapping (was build.ps1's inline array):
  --onefile        -> everything passed to EXE(), no COLLECT()
  --windowed       -> console=False
  --noupx          -> upx=False (UPX-packed exes trigger more antivirus
                      false positives and start slower)
  --name <n>       -> name=<n>
  --icon app.ico   -> icon="app.ico"
  --version-file   -> version="version_info.txt"
  --add-data "app.ico;." -> datas entry ("app.ico", ".")
  --collect-submodules <pkg> / --collect-all yt_dlp / --hidden-import ...
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

TEMPLATE = """# -*- mode: python ; coding: utf-8 -*-
# GENERATED by tools/generate_spec.py -- edit tools/generate_spec.py, not this file.
# yt_dlp loads its site extractors dynamically, hence collect_all; pyttsx3 picks
# its speech driver at run time.  upx=False: UPX-packed exes trigger far more
# antivirus false positives and start slower.

from PyInstaller.utils.hooks import collect_all, collect_submodules

yt_dlp_datas, yt_dlp_binaries, yt_dlp_hidden = collect_all("yt_dlp")

a = Analysis(
    ["run_autodj.py"],
    datas=[("app.ico", "."), *yt_dlp_datas],
    binaries=yt_dlp_binaries,
    hiddenimports=[
        "comtypes",
        "pyperclip",
        "mutagen",
        *collect_submodules("camfrog_autodj"),
        *collect_submodules("pywinauto"),
        *collect_submodules("pyttsx3"),
        *yt_dlp_hidden,
    ],
    noarchive=False,
)

pyz = PYZ(a.pure)

exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    name={name!r},
    icon="app.ico",
    version="version_info.txt",
    console=False,
    upx=False,
)
"""


def render(name: str) -> str:
    """Return the spec source for an exe named ``name``."""
    if not name or "\\" in name or "/" in name:
        raise ValueError(f"invalid exe name: {name!r}")
    return TEMPLATE.format(name=name)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", default="AutoDJ", help="exe name (default: AutoDJ)")
    parser.add_argument("--output", default="AutoDJ.spec", help="spec path to write")
    args = parser.parse_args(argv)

    try:
        spec = render(args.name)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(spec, encoding="utf-8")
    print(f"Generated {out} (name={args.name}) from tools/generate_spec.py")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
